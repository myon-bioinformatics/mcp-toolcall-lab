#!/usr/bin/env python3
"""Regenerate src/mcp_toolcall_lab/static/terminal.css from PySaiyanWeBoo's web_ui.

The stub pages' page shell is PySaiyanWeBoo's ``core_css("terminal")`` (tokens, base, components and the
terminal theme: ``# `` titles, ``[tags]``, ``> `` buttons) plus the few lab-only layout rules below. The file is
committed so the stdlib-only stub server and ``write_pages()`` can serve it without web_ui installed;
``tests/test_stub_pages.py`` fails when it drifts from this generator.

    uv run --extra test python scripts/build_terminal_css.py          # rewrite
    uv run --extra test python scripts/build_terminal_css.py --check  # exit 1 when stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "mcp_toolcall_lab" / "static" / "terminal.css"

HEADER = """/* Generated by scripts/build_terminal_css.py -- do not edit by hand.
 * PySaiyanWeBoo web_ui.core_css("terminal") (pinned in pyproject's test extra) plus the lab-only layout
 * rules at the end. Converted Markdown content keeps vendor/markdown.py's default_stylesheet(). */
"""

LAB_RULES = """/* lab layout: the published stub report (write_pages) and the local /wiki and /pixiv surfaces */
.term-shell{max-width:60rem;margin:0 auto}
.term-header{display:flex;flex-wrap:wrap;align-items:baseline;justify-content:space-between;gap:.75rem;border-bottom:1px solid var(--ui-border);padding-bottom:.75rem;margin-bottom:1rem}
.term-meta{display:flex;gap:.5rem}
.term-workspace{display:grid;grid-template-columns:minmax(0,2fr) minmax(0,1fr);gap:1.5rem;align-items:start}
@media(max-width:720px){.term-workspace{grid-template-columns:1fr}}
#pages-nav a{border:1px solid transparent;padding:.1rem .4rem}
#pages-nav a[aria-current=page]{border-color:var(--ui-border);color:var(--ui-accent)}
#pages-nav a[aria-current=page]::before{content:"> "}
label{display:inline-block;color:var(--ui-muted);margin-right:.4rem}
textarea{width:100%;min-height:4rem}select{width:100%;margin:.4rem 0}
input,select,textarea{font:inherit;background:#05080a;color:var(--ui-fg);border:1px solid var(--ui-border);padding:.35rem .5rem}
[data-cache=hit]{color:var(--ui-accent)}[data-cache=miss]{color:#f2b880}[data-cache=error]{color:var(--ui-danger)}
[role=alert]{border:1px solid var(--ui-danger);color:var(--ui-danger);padding:.5rem}
#build-meta{color:var(--ui-muted);font-size:.9em}
"""


def render() -> str:
    import web_ui  # PySaiyanWeBoo

    return HEADER + web_ui.core_css("terminal") + LAB_RULES


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale")
    args = parser.parse_args(argv)
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current == text:
            return 0
        print(f"{TARGET} is stale; run scripts/build_terminal_css.py", file=sys.stderr)
        return 1
    TARGET.write_text(text, encoding="utf-8")
    print(f"{TARGET} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
